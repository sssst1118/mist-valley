namespace XingGame.Systems.Buffs;

/// <summary>
/// 一条限时增益作用在**哪个属性**上——§8.3「修炼速度的其他影响因素」那张表里的一行因素，
/// 落到代码里的落点。数据在 <c>data/buffs/buffs.json</c>。
/// </summary>
/// <remarks>
/// <para>
/// <b>只有「今天真有消费者、文档又给了出处」的属性才在枚举里</b>（铁律 11）：<see cref="CultivationSpeed"/>
/// 的读者是 <c>CultivationSystem.SpeedMultiplierAt</c> 的第五项，<see cref="MoveSpeed"/> 的读者是
/// <c>PlayerMotor</c>。多一档就会长出一批谁都读不到的数——而编出来的数与真数据长得一模一样，
/// 将来没人分得清「文档写了」与「我们编的」。
/// </para>
/// <para>
/// <b>§12.4 的南瓜派（「恢复 200 体力，耕种 +2」）刻意没有对应成员（不是漏做）</b>：它加的是
/// **耕种类技能等级**，而这个游戏里连「耕种等级」这个属性都还不存在（同一句里的「体力」也一样）
/// ——加一个成员出来，它就只会是一条永远查不到东西、也没有任何代码会读的数据。等耕作技能落地时
/// 再加，那一刻它自然有调用方。同一句话也解释了为什么本枚举的增益**只有乘数没有加法**：
/// 今天有出处的两条（聚气散 +50%、轻身术 +20%）全是乘数，而南瓜派那条加法连目标属性都还没有。
/// </para>
/// <para>
/// <b>枚举成员名就是数据表里的 id</b>（加载时逐字对，不收数字）：<c>Enum.TryParse</c> 连 "0" 都收，
/// 放行它就等于允许按序号写目标——往枚举中间插一项时，旧数据会静默指向另一个属性
/// （同 <c>SpellEffect</c> 的写法）。
/// </para>
/// </remarks>
public enum BuffTarget
{
    /// <summary>
    /// 修炼速度：§8.3 表里的「丹药」那一行（「如『聚气散』+50% 持续 7 天」）与 §12.4 的灵芽羹
    /// （「修炼速度 +20% 持续 1 天」）。读者是打坐的合成器——它是那一行的**第五项**。
    /// </summary>
    CultivationSpeed,

    /// <summary>
    /// 移动速度：§8.2 炼气 7-9 层那一格的「轻身术（移动速度 +20%）」，时长见备案 #78。
    /// 读者是 <c>PlayerMotor</c>（桥接层把这一项喂进 <c>Step</c>）。
    /// </summary>
    MoveSpeed,
}
