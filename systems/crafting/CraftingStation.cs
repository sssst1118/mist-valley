namespace XingGame.Systems.Crafting;

/// <summary>
/// 制作台。四个台子<b>照抄</b> §12.3（<c>docs/public/design.md</c> 第 1339 行）：
/// 「制作台：背包内制作、工坊制作、炼丹房、炼器阁」。
/// </summary>
/// <remarks>
/// <para>
/// <b>「哪条配方在哪个台上做」文档没给</b>（未定义项备案 #62 当初记的就是这件事）。所以第一档是
/// <see cref="Unassigned"/>：它的意思是<b>「文档没说」</b>，不是「哪个台子都行」，更不许拿它当
/// <see cref="Backpack"/> 用。能推的照 §6.7 的建筑功能表推（炼丹房「炼制丹药」、炼器阁「打造法宝」、
/// 工坊「杂交、制作」），推不出来的<b>一律留 Unassigned</b>。
/// </para>
/// <para>
/// <b>今天没有运行期闸门，这是刻意的</b>：§6.7 那三座建筑（工坊 / 炼丹房 / 炼器阁）一个都还不存在
/// （建筑系统不在已排期的切片里），所以「站在炼丹房才能炼筑基丹」这句话今天无处可依——没有建筑，
/// 就没有「玩家此刻站在哪个台子」这个事实可查。这一位先落进数据，等建筑落地再谈闸门。
/// </para>
/// <para>
/// <b>没有「厨房」这一档</b>（刻意不设）：§12.4 的烹饪是另一套系统，§17.2 的菜单里「制作」与「烹饪」
/// 也是两个菜单。把厨房塞进制作台枚举，等于让两套系统在数据类型上先纠缠起来——三道料理因此留
/// Unassigned，见 <c>RecipeTable</c> 的类注释。同款理由：§8.8 的聚灵阵既不是这四个台子做的，
/// 也不在四档里（§13.2 把它跟「修炼室、炼丹房」并列成房屋升级解锁的东西）。
/// </para>
/// </remarks>
public enum CraftingStation
{
    /// <summary>文档没给（备案 #62）。**刻意留的一档，不是漏做**。</summary>
    Unassigned,

    Backpack,           // 背包内制作

    Workshop,           // 工坊制作（§6.7 工坊：杂交、制作）

    AlchemyRoom,        // 炼丹房（§6.7：炼制丹药）

    ArtifactPavilion,   // 炼器阁（§6.7：打造法宝）
}
